"""Write the appendix tables as LaTeX from the code and the result files.

    python3 experiments/make_tables.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "experiments" / "results"
OUT = ROOT.parent / "deductive_multi_agent_system_(MAS)_paper" / "tables.tex"
sys.path.insert(0, str(ROOT / "src"))

from deductive_mas.data.heldout import all_heldout_problems, all_heldout_submissions
from deductive_mas.data.problems import all_problems
from deductive_mas.data.submissions import all_submissions
from deductive_mas.knowledge.misconceptions import MISCONCEPTIONS, RULES, MODEL_ONLY
from deductive_mas.knowledge.ontology import knowledge_graph


def tex(s: str) -> str:
    return (s.replace("\\", "\\textbackslash{}").replace("&", "\\&").replace("%", "\\%")
             .replace("_", "\\_").replace("#", "\\#").replace("{", "\\{").replace("}", "\\}"))


def load(name):
    path = RESULTS / name
    return json.loads(path.read_text()) if path.exists() else None


out = ["% Generated by experiments/make_tables.py — do not edit by hand."]

# taxonomy
rule_ids = {r.misconception_id for r in RULES}
out.append(r"""
\begin{table}[h]
  \caption{The misconception taxonomy. Each belief implicates the listed concepts of the knowledge graph; ``rule'' marks beliefs with a symbolic, dynamic or cost rule, ``model'' the one belief only the reasoning backend (or the offline greedy heuristic) can supply evidence for.}
  \label{tab:taxonomy}
  \centering
  \scriptsize
  \setlength{\tabcolsep}{3pt}
  \begin{tabular}{l>{\raggedright\arraybackslash}p{3.4cm}>{\raggedright\arraybackslash}p{3.9cm}l}
    \toprule
    id & name & implicated concepts & evidence \\
    \midrule""")
for m in MISCONCEPTIONS.values():
    kind = "rule" if m.mid in rule_ids else ("model" if m.mid in MODEL_ONLY else "--")
    out.append(f"    \\code{{{tex(m.mid)}}} & {tex(m.name)} & {tex(', '.join(m.concepts))} & {kind} \\\\")
out.append(r"""    \bottomrule
  \end{tabular}
\end{table}
""")

# curriculum
graph = knowledge_graph()
out.append(r"""
\begin{table}[h]
  \caption{The 65-concept prerequisite graph by stratum (difficulty in logits in parentheses; prerequisites after the colon).}
  \label{tab:graph}
  \centering
  \scriptsize
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{l>{\raggedright\arraybackslash}p{10.6cm}}
    \toprule
    stratum & concepts \\
    \midrule""")
for stratum, members in graph.strata().items():
    items = []
    for cid in members:
        c = graph.concept(cid)
        pre = ", ".join(c.prerequisites) if c.prerequisites else "--"
        items.append(f"\\code{{{tex(cid)}}} ({c.difficulty:+.1f}): {tex(pre)}")
    out.append(f"    {tex(stratum)} & {'; '.join(items)} \\\\")
out.append(r"""    \bottomrule
  \end{tabular}
\end{table}
""")

# banks
def bank_table(problems, submissions, label, caption):
    out.append(f"""
\\begin{{table}}[h]
  \\caption{{{caption}}}
  \\label{{{label}}}
  \\centering
  \\scriptsize
  \\setlength{{\\tabcolsep}}{{4pt}}
  \\begin{{tabular}}{{ll>{{\\raggedright\\arraybackslash}}p{{5.0cm}}l}}
    \\toprule
    task & submission & gold labels & correct \\\\
    \\midrule""")
    for spec in problems:
        for sub in submissions:
            if sub.problem_id != spec.pid:
                continue
            gold = ", ".join(f"\\code{{{tex(g)}}}" for g in sub.gold_misconceptions) or "--"
            out.append(f"    \\code{{{tex(spec.pid)}}} & \\code{{{tex(sub.sid)}}} & {gold} & {'yes' if sub.functionally_correct else 'no'} \\\\")
    out.append(r"""    \bottomrule
  \end{tabular}
\end{table}
""")

bank_table(all_problems(), all_submissions(), "tab:devbank",
           "The development bank: 29 submissions to six tasks. ``correct'' marks programs that return the required output on every valid input (a correct program can still carry a cost or hygiene belief).")
bank_table(all_heldout_problems(), all_heldout_submissions(), "tab:heldbank",
           "The held-out bank: 31 submissions to six tasks written after the rules were frozen, labelled before the system ran.")

# error analysis
held = load("rq1_heldout_full_offline.json")
SYSTEMS = [("det.", "rq1_heldout_full_offline.json"),
           ("+120b", "rq1_heldout_full_gpt-oss-120b.json"),
           ("+20b", "rq1_heldout_full_gpt-oss-20b.json"),
           ("120b only", "rq1_heldout_modelonly_gpt-oss-120b.json")]
if held:
    columns = []
    for header, name in SYSTEMS:
        data = load(name)
        if data is None or data.get("degraded_rows", 0):
            continue
        columns.append((header, {r["submission"]: r for r in data["rows"]}))

    def mark(row):
        """checkmark: headline is gold; circ: gold reported below the headline;
        dash: nothing reported; times: only wrong beliefs reported.
        """
        if row["correct"]:
            return "\\checkmark"
        if not row["predicted"]:
            return "--"
        if set(row["predicted"]) & set(row["gold"]):
            return "$\\circ$"
        return "$\\times$"

    out.append(r"""
\begin{table}[h]
  \caption{Every held-out submission under the four systems of \cref{tab:rq1}. \checkmark: the headline belief is a gold label; $\circ$: a gold label is reported but not as the headline; --: nothing reported; $\times$: only wrong beliefs reported. ``det.'' is the deterministic evaluator, ``+120b'' and ``+20b'' the evaluator with \model{} or \smallmodel{} fused, ``120b only'' \model{} alone. The wrong and missing headlines are discussed in the text.}
  \label{tab:helderrors}
  \centering
  \scriptsize
  \setlength{\tabcolsep}{4pt}
  \begin{tabular}{l>{\raggedright\arraybackslash}p{4.7cm}""" + "c" * len(columns) + r"""}
    \toprule
    submission & gold & """ + " & ".join(h for h, _ in columns) + r""" \\
    \midrule""")
    for r in held["rows"]:
        gold = " ".join("\\code{" + tex(g) + "}" for g in r["gold"])
        marks = " & ".join(mark(rows[r["submission"]]) for _, rows in columns)
        out.append(f"    \\code{{{tex(r['submission'])}}} & {gold} & {marks} \\\\")
    out.append(r"""    \bottomrule
  \end{tabular}
\end{table}
""")

