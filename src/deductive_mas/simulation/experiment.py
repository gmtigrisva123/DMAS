"""The RQ2 A/B experiment.

Split a cohort into control (direct explanations) and treatment (the
deductive system), give a post test on modified harder problems and compare
with t-tests and effect sizes.

- randomisation is stratified by ability and by misconception so the arms
  are balanced on the two variables that dominate the outcome
- the post test is a transfer test: re-testing the same problem only shows
  the student can repeat a fix, a harder variant shows whether the belief
  changed
"""

