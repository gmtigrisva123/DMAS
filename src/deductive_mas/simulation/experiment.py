DISCLAIMER = (
    "SIMULATED COHORT. These outcomes are generated by the response model in "
    "deductive_mas.simulation.student, not observed from human participants. They validate "
    "the analysis pipeline and quantify the system's targeting quality under stated "
    "assumptions; they are not evidence about human learning."
)


@dataclass
class ArmOutcome:
    """Per participant measurements for one arm."""

    arm: str
    retention: List[float] = field(default_factory=list)
    repeat_error: List[float] = field(default_factory=list)
    mastery_gain: List[float] = field(default_factory=list)
    diagnosed: List[float] = field(default_factory=list)
    on_target: List[float] = field(default_factory=list)
    in_zpd: List[float] = field(default_factory=list)
    leakage: List[float] = field(default_factory=list)

    @property
    def n(self) -> int:
        return len(self.retention)

    def summary(self) -> Dict[str, float]:
        def describe(values: List[float]) -> Tuple[float, float]:
            return (mean(values), stdev(values)) if len(values) > 1 else (
                (values[0], 0.0) if values else (0.0, 0.0)
            )

        retention_mean, retention_sd = describe(self.retention)
        repeat_mean, repeat_sd = describe(self.repeat_error)
        gain_mean, _ = describe(self.mastery_gain)
        return {
            "n": float(self.n),
            "retention_mean": retention_mean,
            "retention_sd": retention_sd,
            "repeat_error_mean": repeat_mean,
            "repeat_error_sd": repeat_sd,
            "mastery_gain_mean": gain_mean,
            "diagnostic_hit_rate": mean(self.diagnosed) if self.diagnosed else 0.0,
            "on_target_rate": mean(self.on_target) if self.on_target else 0.0,
            "in_zpd_rate": mean(self.in_zpd) if self.in_zpd else 0.0,
            "max_leakage": max(self.leakage) if self.leakage else 0.0,
        }


@dataclass
class Comparison:
    """One treatment vs control contrast on one outcome."""

    measure: str
    treatment: str
    control: str
    treatment_mean: float
    control_mean: float
    parametric: TestResult
    nonparametric: TestResult
    effect: Any
    ordinal: Any

    def as_row(self) -> Dict[str, Any]:
        return {
            "measure": self.measure,
            "contrast": f"{self.treatment} vs {self.control}",
            "treatment_mean": round(self.treatment_mean, 4),
            "control_mean": round(self.control_mean, 4),
            "welch": self.parametric.apa(),
            "mann_whitney": self.nonparametric.apa(),
            "hedges_g": str(self.effect),
            "cliffs_delta": str(self.ordinal),
        }


@dataclass
class ExperimentResult:
    seed: int
    arms: Dict[str, ArmOutcome] = field(default_factory=dict)
    comparisons: List[Comparison] = field(default_factory=list)
    corrections: List[Adjusted] = field(default_factory=list)
    power: Dict[str, float] = field(default_factory=dict)
    disclaimer: str = DISCLAIMER

    def to_dict(self) -> Dict[str, Any]:
        return {
            "seed": self.seed,
            "disclaimer": self.disclaimer,
            "arms": {name: arm.summary() for name, arm in self.arms.items()},
            "comparisons": [c.as_row() for c in self.comparisons],
            "corrections": [
                {"hypothesis": a.label, "p": round(a.raw, 5),
                 "p_adjusted": round(a.adjusted, 5), "rejected": a.rejected}
                for a in self.corrections
            ],
            "power": {k: round(v, 4) for k, v in self.power.items()},
        }


class Experiment:
    """Runs the randomised comparison end to end."""

    def __init__(
        self,
        config: Optional[Config] = None,
        *,
        orchestrator: Optional[DeductiveOrchestrator] = None,
        response_model: Optional[ResponseModel] = None,
    ):
        self.config = config or Config()
        self.graph = knowledge_graph()
        self.tracker = MasteryTracker(self.graph, self.config.knowledge)
        self.orchestrator = orchestrator or DeductiveOrchestrator(self.config)
        self.population = StudentPopulation(self.graph, self.tracker, model=response_model)

    # run
    def run(
        self,
        *,
        students: int = 120,
        seed: int = 20260909,
        sessions: int = 2,
        include_ablation: bool = True,
    ) -> ExperimentResult:
        rng = random.Random(seed)
        catalogue = self._catalogue()
        pool = sorted({mid for mid, _ in catalogue})
        cohort = self.population.sample(students, seed=seed, misconception_pool=pool)

        arms: List[Tutor] = [DirectAnswerTutor(), DeductiveTutor(self.orchestrator)]
        if include_ablation:
            arms.append(UntargetedSocraticTutor(self.orchestrator))
        assignment = self._stratified_assignment(cohort, len(arms), rng)

        outcomes = {tutor.arm: ArmOutcome(arm=tutor.arm) for tutor in arms}
        items = self._transfer_items()

        for profile, arm_index in zip(cohort, assignment):
            tutor = arms[arm_index]
            local = random.Random(seed ^ hash(profile.sid) & 0xFFFFFFFF)
            before = _mean_mastery(profile)
            transfer_retention = 1.0
            turns = 0
            aggregate: Dict[str, float] = {"diagnosed": 0.0, "on_target": 0.0, "in_zpd": 0.0}
            leakage = 0.0

            for _ in range(sessions):
                choice = self._choose_task(profile, catalogue, local)
                if choice is None:
                    break
                misconception_id, submission = choice
                spec = get_problem(submission.problem_id)
                turn = tutor.teach(spec, submission, rng=local)
                effect = self.population.apply_intervention(
                    profile,
                    misconception_id=misconception_id,
                    diagnosed=turn.diagnosed,
                    target_concept=turn.target_concept,
                    zpd_probability=turn.zpd_probability,
                    socratic=turn.socratic,
                    rng=local,
                )
                transfer_retention = effect["transfer_retention"]
                leakage = max(leakage, turn.leakage)
                for key in aggregate:
                    aggregate[key] += effect[key]
                turns += 1

            if turns == 0:
                continue
            score, repeats = self.population.post_test(
                profile, items, transfer_retention=transfer_retention, rng=local
            )
            record = outcomes[tutor.arm]
            record.retention.append(score)
            record.repeat_error.append(repeats)
            record.mastery_gain.append(_mean_mastery(profile) - before)
            record.diagnosed.append(aggregate["diagnosed"] / turns)
            record.on_target.append(aggregate["on_target"] / turns)
            record.in_zpd.append(aggregate["in_zpd"] / turns)
            record.leakage.append(leakage)

        result = ExperimentResult(seed=seed, arms=outcomes)
        self._analyse(result, rng)
        return result

    # analysis
    def _analyse(self, result: ExperimentResult, rng: random.Random):
        control = result.arms.get(DirectAnswerTutor.arm)
        if control is None or control.n < 2:
            return
        measures = (
            ("knowledge retention", "retention", "greater"),
            ("recurring error rate", "repeat_error", "less"),
            ("mastery gain", "mastery_gain", "greater"),
        )
        p_values: List[Tuple[str, float]] = []
        for arm_name, arm in result.arms.items():
            if arm_name == control.arm or arm.n < 2:
                continue
            for label, attribute, direction in measures:
                treatment_values = getattr(arm, attribute)
                control_values = getattr(control, attribute)
                if len(treatment_values) < 2 or len(control_values) < 2:
                    continue
                parametric = welch_t_test(treatment_values, control_values, alternative=direction)
                nonparametric = mann_whitney_u(
                    treatment_values, control_values, alternative=direction
                )
                effect = effect_with_ci(
                    treatment_values, control_values, resamples=1200, rng=random.Random(rng.random())
                )
                ordinal = cliffs_delta(treatment_values, control_values)
                comparison = Comparison(
                    measure=label,
                    treatment=arm_name,
                    control=control.arm,
                    treatment_mean=mean(treatment_values),
                    control_mean=mean(control_values),
                    parametric=parametric,
                    nonparametric=nonparametric,
                    effect=effect,
                    ordinal=ordinal,
                )
                result.comparisons.append(comparison)
                p_values.append((f"{arm_name}/{label}", parametric.p_value))

        result.corrections = holm_bonferroni(p_values, alpha=0.05)
        treatment = result.arms.get(DeductiveTutor.arm)
        if treatment and treatment.n >= 2:
            n = min(treatment.n, control.n)
            observed = hedges_g(treatment.retention, control.retention).value
            result.power = {
                "n_per_arm": float(n),
                "observed_effect": observed,
                "achieved_power": two_sample_power(abs(observed), n),
                "minimum_detectable_effect": minimum_detectable_effect(n),
            }

    # plumbing
    def _catalogue(self) -> List[Tuple[str, Submission]]:
        """(misconception, submission) pairs the cohort can be given."""
        out: List[Tuple[str, Submission]] = []
        for submission in all_submissions():
            for misconception_id in submission.gold_misconceptions:
                if misconception_id in MISCONCEPTIONS:
                    out.append((misconception_id, submission))
        return out

    def _choose_task(
        self,
        profile: StudentProfile,
        catalogue: Sequence[Tuple[str, Submission]],
        rng: random.Random,
    ) -> Optional[Tuple[str, Submission]]:
        """Give the learner a task showing a misconception they actually hold."""
        matching = [pair for pair in catalogue if pair[0] in profile.misconceptions]
        if not matching:
            return None
        return matching[rng.randrange(len(matching))]

    def _stratified_assignment(
        self, cohort: Sequence[StudentProfile], arms: int, rng: random.Random
    ) -> List[int]:
        """Balance arms on ability and held misconceptions.
        Sort by the stratifying variables then deal arms round robin in each block,
        which gives near perfect balance (simple randomisation only does that in
        expectation).
        """
        order = sorted(
            range(len(cohort)),
            key=lambda i: (sorted(cohort[i].misconceptions), cohort[i].ability),
        )
        assignment = [0] * len(cohort)
        offset = rng.randrange(arms)
        for position, index in enumerate(order):
            assignment[index] = (position + offset) % arms
        return assignment

    def _transfer_items(self) -> List[Item]:
        """Post test of harder variants."""
        items: List[Item] = []
        for spec in all_problems():
            items.append(
                Item(
                    iid=f"transfer::{spec.pid}",
                    difficulty=spec.difficulty + 0.6,     # harder variant
                    discrimination=spec.discrimination,
                    guessing=spec.guessing,
                    concepts=spec.concepts,
                    title=spec.title,
                )
            )
        return items


def _mean_mastery(profile: StudentProfile) -> float:
    if profile.mastery is None:
        return 0.0
    return profile.mastery.mean()
